-- NLGEP Chat social features: profiles, friends, direct messages, group chats.
-- Already applied to the NLGEP AI Supabase project (migration "chat_social_features").
-- Kept here so the schema is in the repo. Safe to run again.
-- Note: chat_users.user_id is a uuid, so every user reference below is a uuid too.

create table if not exists public.chat_profiles (
  user_id uuid primary key references public.chat_users(user_id) on delete cascade,
  bio text not null default '' check (char_length(bio) <= 200),
  status text not null default '' check (char_length(status) <= 60),
  avatar text not null default '🙂' check (char_length(avatar) between 1 and 16),
  color text not null default '#a9d4bb' check (color ~ '^#[0-9a-fA-F]{6}$'),
  updated_at timestamptz not null default now()
);

create table if not exists public.chat_friendships (
  friendship_id bigint generated by default as identity primary key,
  requester_id uuid not null references public.chat_users(user_id) on delete cascade,
  addressee_id uuid not null references public.chat_users(user_id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'accepted')),
  created_at timestamptz not null default now(),
  check (requester_id <> addressee_id)
);

-- one row per pair of people, whoever asked first
create unique index if not exists chat_friendships_pair_idx
  on public.chat_friendships (least(requester_id, addressee_id), greatest(requester_id, addressee_id));
create index if not exists chat_friendships_requester_idx on public.chat_friendships(requester_id);
create index if not exists chat_friendships_addressee_idx on public.chat_friendships(addressee_id);

-- a room is either a direct message (kind = 'dm') or a group chat (kind = 'group')
create table if not exists public.chat_rooms (
  room_id uuid primary key default gen_random_uuid(),
  kind text not null check (kind in ('dm', 'group')),
  name text not null default '' check (char_length(name) <= 40),
  owner_id uuid references public.chat_users(user_id) on delete set null,
  dm_key text unique,
  created_at timestamptz not null default now(),
  last_message_at timestamptz not null default now(),
  last_message_id bigint,
  last_username text,
  last_preview text
);

create table if not exists public.chat_room_members (
  room_id uuid not null references public.chat_rooms(room_id) on delete cascade,
  user_id uuid not null references public.chat_users(user_id) on delete cascade,
  status text not null default 'active' check (status in ('invited', 'active')),
  invited_by uuid,
  joined_at timestamptz not null default now(),
  primary key (room_id, user_id)
);

create index if not exists chat_room_members_user_idx on public.chat_room_members(user_id);

create table if not exists public.chat_room_messages (
  message_id bigint generated by default as identity primary key,
  room_id uuid not null references public.chat_rooms(room_id) on delete cascade,
  user_id uuid not null references public.chat_users(user_id) on delete cascade,
  username text not null,
  content text not null check (char_length(content) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists chat_room_messages_room_idx
  on public.chat_room_messages(room_id, message_id desc);

-- Private server-side tables. The app uses the Supabase service_role key.
alter table public.chat_profiles enable row level security;
alter table public.chat_friendships enable row level security;
alter table public.chat_rooms enable row level security;
alter table public.chat_room_members enable row level security;
alter table public.chat_room_messages enable row level security;

grant all privileges on table public.chat_profiles to service_role;
grant all privileges on table public.chat_friendships to service_role;
grant all privileges on table public.chat_rooms to service_role;
grant all privileges on table public.chat_room_members to service_role;
grant all privileges on table public.chat_room_messages to service_role;

grant all privileges on sequence public.chat_friendships_friendship_id_seq to service_role;
grant all privileges on sequence public.chat_room_messages_message_id_seq to service_role;

notify pgrst, 'reload schema';
